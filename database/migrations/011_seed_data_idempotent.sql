-- ═══════════════════════════════════════════════════════════
--  DATA INTEGRITY VALIDATION
-- ═══════════════════════════════════════════════════════════
DO $$
DECLARE
    total_rules INT;
    total_auto_rules INT;
    total_cron INT;
    total_faq INT;
    invalid_cron INT;
    faq_without_category INT;
BEGIN
    -- Count rows
    SELECT COUNT(*) INTO total_rules FROM bot_config.business_rules WHERE deleted_at IS NULL;
    SELECT COUNT(*) INTO total_auto_rules FROM bot_config.auto_answer_rules WHERE deleted_at IS NULL;
    SELECT COUNT(*) INTO total_cron FROM bot_config.cron_jobs WHERE deleted_at IS NULL;
    SELECT COUNT(*) INTO total_faq FROM knowledge.faq WHERE deleted_at IS NULL;

    -- Validate cron job frequencies are reasonable (not too frequent)
    SELECT COUNT(*) INTO invalid_cron
    FROM bot_config.cron_jobs
    WHERE frequency_seconds < 60 -- Less than 1 minute is suspicious
    AND deleted_at IS NULL;

    -- Validate FAQ categories reference valid topics
    SELECT COUNT(*) INTO faq_without_category
    FROM knowledge.faq
    WHERE category IS NULL
       OR category NOT IN (SELECT topic FROM bot_config.auto_answer_rules)
    AND deleted_at IS NULL;

    -- Report validation results
    RAISE NOTICE '📊 Data Integrity Validation:';
    RAISE NOTICE '   business_rules: %', total_rules;
    RAISE NOTICE '   auto_answer_rules: %', total_auto_rules;
    RAISE NOTICE '   cron_jobs: %', total_cron;
    RAISE NOTICE '   faq entries: %', total_faq;

    IF invalid_cron > 0 THEN
        RAISE WARNING '⚠️  % cron jobs have frequency < 60s (may cause resource exhaustion)', invalid_cron;
    ELSE
        RAISE NOTICE '   ✅ All cron job frequencies are reasonable';
    END IF;

    IF faq_without_category > 0 THEN
        RAISE WARNING '⚠️  % FAQ entries have invalid categories', faq_without_category;
    ELSE
        RAISE NOTICE '   ✅ All FAQ entries reference valid categories';
    END IF;

    -- Validate embeddings dimension (if any exist)
    IF total_faq > 0 THEN
        DECLARE
            wrong_dim INT;
        BEGIN
            SELECT COUNT(*) INTO wrong_dim
            FROM knowledge.faq
            WHERE embedding IS NOT NULL
            AND vector_dims(embedding) != 1536;

            IF wrong_dim > 0 THEN
                RAISE WARNING '⚠️  % FAQ entries have wrong embedding dimension (expected 1536)', wrong_dim;
            ELSE
                RAISE NOTICE '   ✅ All FAQ embeddings have correct dimension';
            END IF;
        END;
    END IF;
END $$;

