-- Helper function to get business rule value
CREATE OR REPLACE FUNCTION get_business_rule(rule_name_param TEXT)
RETURNS TEXT AS $$
DECLARE
    rule_val JSONB;
BEGIN
    SELECT rule_value INTO rule_val
    FROM bot_config.business_rules
    WHERE rule_name = rule_name_param
    AND deleted_at IS NULL;

    RETURN rule_val->>'value';
END;
$$ LANGUAGE plpgsql;

